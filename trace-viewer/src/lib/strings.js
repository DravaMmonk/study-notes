/** Look up a string in a language, filling {placeholders} from vars. */
export function translate(lang, key, vars = {}) {
  const pair = STRINGS[key]
  const text = pair ? pair[lang === 'en' ? 1 : 0] : key
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '')
}
