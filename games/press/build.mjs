// Vision Complete's map illustration (the filter press from the notes, trace-viewer/src/figures/conv) as one module
// for the games hub, which ships as plain files. The figure host is reused as is; only its registry, which needs
// Vite's import.meta.glob, is swapped for one that knows this figure.
//
//   node games/press/build.mjs    writes press.js next to this file (needs trace-viewer's node_modules)

import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FIGURES = join(HERE, '../../trace-viewer/src/figures');
const { build } = createRequire(join(HERE, '../../trace-viewer/package.json'))('esbuild');

const registry = {
  name: 'registry',
  setup(b) {
    b.onResolve({ filter: /\/registry\.js$/ }, () => ({ path: 'registry', namespace: 'press' }));
    b.onLoad({ filter: /.*/, namespace: 'press' }, () => ({ contents: `export const figures = { 'conv-press': () => import('./conv/figure.js') }`, resolveDir: FIGURES }));
  },
};

const entry = `import { createFigureHost } from './host.js'
// Mounts the press into el, without its card, following the page's theme. Returns the cleanup.
export function mountPress(el, { lang = 'zh' } = {}) {
  const figure = createFigureHost('conv-press', document.documentElement.dataset.theme, { lang, bare: true })
  el.replaceChildren(figure.host)
  const themes = new MutationObserver(() => figure.setTheme(document.documentElement.dataset.theme))
  themes.observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] })
  return () => { themes.disconnect(); figure.dispose() }
}`;

await build({
  stdin: { contents: entry, resolveDir: FIGURES, sourcefile: 'press-entry.js' },
  bundle: true,
  format: 'esm',
  target: 'es2020',
  outfile: join(HERE, 'press.js'),
  plugins: [registry],
  banner: { js: '// Generated by build.mjs from trace-viewer/src/figures. Do not edit; rebuild after the figure changes.' },
  logLevel: 'info',
});
