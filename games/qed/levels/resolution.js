// Chapter 4 · Resolution: the prover stops being wired step by step and starts searching. Two lines first: rewriting
// (each law proved both ways on the proof board, then put on a card of the machine board, where it rewrites
// everywhere; the cards line up into NNF and CNF), and clauses (resolution proved, then used; the repeat frame runs it
// until ⊥ or nothing new). They meet in refutation: what is known and the negated goal, to CNF, to clauses, saturated.
// The islanders come back, many of them.
import { machine, proof } from '../../kit/domains/logic/build.js'

const T = (zh, en) => ({ zh, en })
// A law's level: prove it both ways on the proof board, then use its card on the machine board.
const law = (task) => ({ kind: 'proof', step: T('证明', 'Prove'), ...task })
const use = (task) => ({ kind: 'machine', step: T('用起来', 'Use it'), ...task })
const KNOWN = T('已知', 'Known')
const CLAIM = T('要证', 'Claim')
const refuteInputs = [{ name: 'known', label: KNOWN }, { name: 'goal', label: CLAIM }]
// What is known and the negated claim, to CNF, to clauses, saturated.
const refutation = machine({ n: ['neg'], c: ['conj'], f: ['cnf'], t: ['toClauses'], s: ['saturate'] }, ['goal>n.in', 'known>c.a', 'n>c.b', 'c>f.in', 'f>t.in', 't>s.in', 's>out'], { inputs: ['known', 'goal'] })
// Islanders: what each says, as one sentence, and claims about them.
const says = (n) => {
  const K = 'ABCDEFGHIJ'.split('').slice(0, n).map((c) => `K${c}`)
  return [...K.slice(0, -1).map((k, i) => `(${k} ↔ ¬${K[i + 1]})`), `(${K.at(-1)} ↔ ¬${K[0]} ∧ ¬${K[1]})`].join(' ∧ ')
}

