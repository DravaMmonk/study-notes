// Chapter 9 · Theories: functions defined by equations, over numbers built from 0 and S, lists built from [] and ::,
// and the machine proves things about them. Simp rewrites with the definitions left to right; where it gets stuck on a
// variable, induction splits the goal into 0 and the step, and the step's hypothesis lets simp through. Each lemma
// proved becomes a card that adds it to simp's rules, so the next proof stands on it: n + 0 = n, then n + S m, then
// commutativity, and for lists xs ++ [] = xs, associativity, then rev (xs ++ ys) and rev (rev xs) = xs. The topic sorts
// by insertion; the challenges are a sum with an accumulator (the lemma must be stated more generally first) and
// commutativity as a rule, which would go round in circles.
