// Chapter 8 · Tactics: the proof state goes on the wire, a list of goals still open, and tactics work on it backwards,
// each doing what a kernel rule does read the other way. First the tactics one by one (take a goal apart by its
// shape, close it with what is known, use a hypothesis up), then combinators: REPEAT is the repeat frame, ORELSE a frame
// of its own, and together they make the player's own auto. The family topic writes rules that a depth-first solver
// answers queries with, where the order of the conditions decides whether it stops.
import { machine, proof } from '../../kit/domains/logic/build.js'
